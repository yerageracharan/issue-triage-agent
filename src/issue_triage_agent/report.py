"""Markdown and JSON report writers."""

from __future__ import annotations

import json
import re
from collections import Counter
from pathlib import Path

from .models import TriageResult


def _escape_markdown(value: str) -> str:
    """Escape untrusted issue/model text before embedding it in Markdown."""
    value = value.replace("\\", "\\\\").replace("\r", " ").replace("\n", " ")
    return re.sub(r"([`*_{}\[\]<>()#+.!|~-])", r"\\\1", value).strip()


def _escape_cell(value: str) -> str:
    return _escape_markdown(value)


def _safe_issue_url(value: str) -> str:
    """Accept only canonical github.com issue URLs from API data or fixtures."""
    if re.fullmatch(r"https://github\.com/[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+/issues/[0-9]+", value):
        return value
    return ""


def _issue_reference(number: int, title: str, url: str) -> str:
    label = f"#{number} — {_escape_markdown(title)}"
    safe_url = _safe_issue_url(url)
    return f"[{label}]({safe_url})" if safe_url else label


def render_markdown(repository: str, results: list[TriageResult]) -> str:
    categories = Counter(item.category for item in results)
    priorities = Counter(item.priority for item in results)
    attention = sum(item.needs_attention for item in results)
    lines = [
        f"# Issue triage report: {_escape_markdown(repository)}",
        "",
        "> Generated by Issue Triage Agent. All classifications and duplicate matches are suggestions; a maintainer must verify them.",
        "",
        "## Overview",
        "",
        f"- Issues analysed: **{len(results)}**",
        f"- Flagged for human attention: **{attention}**",
        f"- Categories: {', '.join(f'{name} ({count})' for name, count in sorted(categories.items())) or 'None'}",
        f"- Provisional priorities: {', '.join(f'{name} ({count})' for name, count in sorted(priorities.items())) or 'None'}",
        "",
        "## Triage queue",
        "",
        "| Issue | Category | Priority | Confidence | Attention |",
        "|---|---|---:|---|---|",
    ]
    for item in sorted(results, key=lambda r: (r.priority, r.issue.number)):
        issue_ref = _issue_reference(item.issue.number, item.issue.title, item.issue.html_url)
        lines.append(f"| {issue_ref} | {item.category} | {item.priority} | {item.confidence} | {'Yes' if item.needs_attention else 'No'} |")

    lines.extend(["", "## Issue details", ""])
    for item in sorted(results, key=lambda r: (r.priority, r.issue.number)):
        issue_ref = f"[#{item.issue.number}]({_safe_issue_url(item.issue.html_url)})" if _safe_issue_url(item.issue.html_url) else f"#{item.issue.number}"
        lines.extend([
            f"### {issue_ref}",
            "",
            f"**Suggested triage:** `{item.category}` · `{item.priority}` · confidence: `{item.confidence}`",
            "",
            "**Why:**",
        ])
        lines.extend(f"- {reason}" for reason in item.rationale)
        lines.extend(["", "**Suggested labels (not applied):**", "", ", ".join(f"`{label}`" for label in item.suggested_labels), ""])
        if item.missing_information:
            lines.extend(["**Information that may be missing:**", ""])
            lines.extend(f"- {missing}" for missing in item.missing_information)
            lines.append("")
        if item.duplicate_candidates:
            lines.extend(["**Possible duplicates — verify manually:**", ""])
            for candidate in item.duplicate_candidates:
                link = _issue_reference(int(candidate["number"]), str(candidate["title"]), str(candidate["url"] or ""))
                lines.append(f"- {link} (heuristic similarity: {candidate['similarity']:.0%})")
            lines.append("")
        if item.llm_summary:
            lines.extend([f"**Local model summary:** {_escape_markdown(item.llm_summary)}", ""])
        if item.llm_follow_up:
            lines.extend([f"**Possible follow-up:** {_escape_markdown(item.llm_follow_up)}", ""])
        lines.append("---")
        lines.append("")

    lines.extend([
        "## Method and limitations",
        "",
        "- Categories and priorities are produced by transparent keyword and label rules, not a trained classifier.",
        "- P0–P3 priorities are provisional signals, not impact assessments or service-level commitments.",
        "- Duplicate detection uses title/body token overlap and string similarity. Similarity is not proof of duplication.",
        "- Missing-information checks look for common headings and phrases. They can miss equivalent wording or flag a report that contains the details in another form.",
        "- The optional local model only supplies an extra summary and follow-up question; it cannot override rule-based triage.",
        "- This tool is read-only. It does not post comments, apply labels, assign issues, or close issues.",
        "",
    ])
    return "\n".join(lines)


def write_reports(repository: str, results: list[TriageResult], output_dir: str | Path) -> tuple[Path, Path]:
    destination = Path(output_dir)
    destination.mkdir(parents=True, exist_ok=True)
    json_path = destination / "triage-report.json"
    markdown_path = destination / "triage-report.md"
    payload = {
        "repository": repository,
        "issue_count": len(results),
        "results": [item.to_dict() for item in results],
    }
    json_path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    markdown_path.write_text(render_markdown(repository, results), encoding="utf-8")
    return markdown_path, json_path
